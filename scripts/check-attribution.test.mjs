import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import {
  checkBranch,
  checkIdentity,
  findAttribution,
  logRange,
} from "./check-attribution.mjs";

const script = fileURLToPath(new URL("./check-attribution.mjs", import.meta.url));
const rules = (text) => findAttribution(text, "test").map((f) => f.rule);

// The fixtures are synthetic: they keep the shape of real attribution
// (footers, trailers, session and task links) without any real identifier.
test("flags attribution shapes in commit and pull-request text", () => {
  assert.deepEqual(
    rules(
      [
        "docs: record the release",
        "",
        "Co-Authored-By: Example Model <noreply@example.com>",
        "Example-Session: https://example.com/code/session_01AbC",
      ].join("\n"),
    ),
    ["co-author-trailer", "session-trailer", "session-link"],
  );
  assert.deepEqual(rules("_Generated by [Tool](https://example.com/code)_"), [
    "generated-by-line",
  ]);
  assert.deepEqual(rules("🤖 Generated with [Tool](https://example.com)"), [
    "generated-by-line",
  ]);
  assert.deepEqual(
    rules('<!-- tool-projects-attribution: {"github_login":"someone"} -->'),
    ["attribution-marker"],
  );
  assert.deepEqual(
    rules("[Agent Task](https://agent.example/tool/tasks/task_e_0123abcd)"),
    ["session-link"],
  );
});

test("accepts ordinary text that uses the same words", () => {
  assert.deepEqual(
    rules(
      [
        "feat: add a site adapter",
        "",
        "The predictor publishes match probabilities and a public evaluation.",
        "The schema is generated with the plugin off.",
        "Do not add co-author trailers; see the provenance rule.",
        "Signed-off-by: Someone <someone@example.com>",
        "Track it in https://example.com/projects/tasks/backlog",
      ].join("\n"),
    ),
    [],
  );
  assert.deepEqual(rules(""), []);
});

test("requires a Conventional Commits type prefix on the head branch", () => {
  for (const branch of ["feat/x", "fix/x", "chore/x", "docs/x", ""]) {
    assert.deepEqual(checkBranch(branch), []);
  }
  for (const branch of ["tool/project-thread-abc", "agent/x", "main"]) {
    assert.deepEqual(
      checkBranch(branch).map((f) => f.rule),
      ["branch-prefix"],
    );
  }
});

test("requires the owner's name and address as author and committer", () => {
  const owner = "155735614+amir42com@users.noreply.github.com";
  const identity = (authorName, authorEmail, committerName, committerEmail) =>
    checkIdentity({
      sha: "0123456789",
      authorName,
      authorEmail,
      committerName,
      committerEmail,
    }).map((f) => f.rule);

  assert.deepEqual(identity("Amir", owner, "Amir", owner), []);
  assert.deepEqual(
    identity("Amir", owner, "GitHub", "noreply@github.com"),
    [],
  );
  assert.deepEqual(
    identity(
      "dependabot[bot]",
      "49699333+dependabot[bot]@users.noreply.github.com",
      "GitHub",
      "noreply@github.com",
    ),
    [],
  );
  assert.deepEqual(
    identity("Tool", "noreply@example.com", "Tool", "noreply@example.com"),
    ["author-identity", "committer-identity"],
  );
  assert.deepEqual(identity("Tool", owner, "Tool", owner), [
    "author-identity",
    "committer-identity",
  ]);
  assert.deepEqual(identity("", "", "", ""), [
    "author-identity",
    "committer-identity",
  ]);
});

test("checks every commit of the head when a push replaced history", () => {
  const base = "a".repeat(40);
  assert.deepEqual(logRange(base, "HEAD", true), [`${base}..HEAD`]);
  assert.deepEqual(logRange(base, "HEAD", false), ["HEAD"]);
  assert.deepEqual(logRange("0".repeat(40), "HEAD", false), ["-1", "HEAD"]);
  assert.deepEqual(logRange(null, "HEAD", false), ["-1", "HEAD"]);
});

test("the command fails on an attributed pull-request body", () => {
  const run = (body) =>
    spawnSync(process.execPath, [script, "--base", "HEAD", "--head", "HEAD"], {
      encoding: "utf8",
      env: { ...process.env, PR_TITLE: "docs: a change", PR_BODY: body },
    });
  assert.equal(run("## What\n\nA change.").status, 0);
  const attributed = run("## What\n\nA change.\n\n_Generated by [Tool](x)_");
  assert.equal(attributed.status, 1);
  assert.match(attributed.stderr, /pull-request body, line 5 \[generated-by-line\]/);
});
